/// Embedded 8x16 bitmap font covering ASCII 32-126 plus box-drawing characters.
/// Each glyph is 8 pixels wide, 16 pixels tall.
/// Each byte is one row, MSB = leftmost pixel.
/// Based on the classic VGA/BIOS 8x16 font (public domain).

pub const FONT_WIDTH: usize = 8;
pub const FONT_HEIGHT: usize = 16;

/// Returns the 16-byte bitmap for any Unicode character.
/// Supports ASCII 32-126, box-drawing U+2500-U+257F, and block elements U+2580-U+259F.
/// Unknown characters return a filled box (missing glyph indicator).
pub fn glyph_char(ch: char) -> &'static [u8; 16] {
    let cp = ch as u32;
    // ASCII range
    if cp >= 32 && cp <= 126 {
        return &FONT_DATA[(cp - 32) as usize];
    }
    // Box drawing: U+2500 - U+257F (128 chars)
    if cp >= 0x2500 && cp <= 0x257F {
        return &BOX_DRAWING[(cp - 0x2500) as usize];
    }
    // Block elements: U+2580 - U+259F (32 chars)
    if cp >= 0x2580 && cp <= 0x259F {
        return &BLOCK_ELEMENTS[(cp - 0x2580) as usize];
    }
    &MISSING_GLYPH
}

